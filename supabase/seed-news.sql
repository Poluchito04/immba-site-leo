透過將學期規劃為16週實體授課與2週自主學習時間，讓學生有機會跳脫固定課表，把學習延伸到教室之外。有人參與講座、進行產業探索，有人安排實地參訪、準備證照，也有人利用這段時間重新思考自己的興趣與未來方向。

真實世界裡不會永遠有人幫你安排好課表。學會主動探索、規劃與學習，也是大學教育重要的一課。

今年的自主學習週，剛好遇上端午佳節。在享受假期、和家人朋友團聚之餘，也別忘了留一點時間給自己，探索想學的事、想看的世界，或想成為的模樣。

